function assertExecutableBoundaries(repoRoot, policy) {
  for (const name of MCP_SERVER_NAMES) {
    const server = policy.mcpServers[name];
    if (server.url) continue;
    const cwd = join(repoRoot, server.cwd);
    if (!server.command) {
      const script = mcpScript(repoRoot, server, name);
      if (!existsSync(script) || !statSync(script).isFile()) throw new Error(`MCP server ${name} script is missing: ${script}`);
    }
    requireDirectory(cwd, `MCP server ${name} cwd`);
  }
}

/**
 * Builds the argv for a stdio MCP server launch: an optional
 * `--env-file-if-exists` node flag (never an inlined secret) ahead of the
 * server script and its own arguments.
 * @param {string} repoRoot
 * @param {object} server
 * @param {string} name
 * @returns {string[]}
 */
function stdioArgs(repoRoot, server, name) {
  return [
    ...(server.envFile ? [`--env-file-if-exists=${server.envFile}`] : []),
    mcpScript(repoRoot, server, name),
    ...(server.arguments ?? []),
  ];
}

function stdioLaunch(repoRoot, server, name, nodeExecutable = process.execPath) {
  const cwd = join(repoRoot, server.cwd);
  if (server.command) return { command: server.command, args: server.arguments ?? [], cwd };
  return { command: nodeExecutable, args: stdioArgs(repoRoot, server, name), cwd };
}

function mcpScript(repoRoot, server, name) {
  if (server.package === undefined) {
    if (typeof server.script !== "string" || server.script.length === 0) throw new Error(`MCP server ${name} has no script`);
    return join(repoRoot, server.script);
  }
  if (typeof server.package !== "string" || typeof server.bin !== "string") throw new Error(`MCP server ${name} package launch must name its package and bin`);
  const root = join(repoRoot, server.cwd, "node_modules", server.package);
  const manifestPath = join(root, "package.json");
  if (!existsSync(manifestPath)) throw new Error(`MCP server ${name} package is not installed: ${server.package}`);
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  const target = typeof manifest.bin === "string" ? manifest.bin : manifest.bin?.[server.bin];
  if (typeof target !== "string" || target.length === 0 || target.startsWith("/") || target.split("/").includes("..")) throw new Error(`MCP server ${name} package does not declare bin ${server.bin}`);
  return join(root, target);
}

export function assertMcpReachability(repoRoot, policy, serverNames = Object.keys(policy.mcpServers ?? {})) {
  const request = `${JSON.stringify({ jsonrpc: "2.0", id: 1, method: "tools/list", params: {} })}\n`;
  for (const name of serverNames) {
    const server = policy.mcpServers[name];
    if (server.enabled !== true) continue;
    const result = server.url
      ? spawnSync(process.execPath, ["-e", `
const { request } = require(process.argv[1].startsWith("https:") ? "node:https" : "node:http");
const payload = process.argv[2];
const req = request(process.argv[1], { method: "POST", headers: { "content-type": "application/json", accept: "application/json", "content-length": Buffer.byteLength(payload) } }, (res) => {
  const chunks = [];
  res.on("data", (chunk) => chunks.push(chunk));
  res.on("end", () => {
    const body = Buffer.concat(chunks).toString("utf8");
    if ((res.statusCode ?? 500) >= 400) { process.stderr.write(body || String(res.statusCode)); process.exitCode = 1; return; }
    process.stdout.write(body);
  });
});
req.on("error", (error) => { process.stderr.write(error.message); process.exitCode = 1; });
req.end(payload);
`, server.url, request], { encoding: "utf8", timeout: (server.startupTimeoutSeconds ?? 10) * 1000 })
      : (() => {
        const launch = stdioLaunch(repoRoot, server, name);
        return spawnSync(launch.command, launch.args, {
          cwd: launch.cwd,
          input: request,
          encoding: "utf8",
          env: { ...process.env, ...(server.environment ?? {}) },
          timeout: (server.startupTimeoutSeconds ?? 10) * 1000,
        });
      })();
    if (result.status !== 0) throw new Error(`MCP server ${name} failed its tools/list handshake: ${result.stderr || result.stdout || `exit ${result.status}`}`);
    let response;
    try { response = JSON.parse(result.stdout); }
    catch { throw new Error(`MCP server ${name} returned a non-JSON tools/list response`); }
    const tools = response.result?.tools ?? response.result?.structuredContent?.tools;
    if (!Array.isArray(tools)) throw new Error(`MCP server ${name} returned no tools list`);
    const observed = new Set(tools.map((tool) => tool.name));
    const missing = server.enabledTools.filter((tool) => !observed.has(tool));
    if (missing.length) throw new Error(`MCP server ${name} does not advertise enabled tools: ${missing.join(", ")}`);
  }
}

export function renderConfig(repoRoot, policy = loadPolicy(), nodeExecutable = process.execPath) {
  const lines = [
    `approval_policy = "on-request"`,
    `sandbox_mode = "workspace-write"`,
    `web_search = "disabled"`,
    "",
    "[features]",
    ...Object.entries({ ...policy.features, multi_agent: policy.agents.enabled }).map(([name, enabled]) => `${name} = ${enabled}`),
    "",
    "[agents]",
    `max_threads = ${policy.agents.maximumConcurrentThreadsPerSession}`,
  ];
  const selectedMcpServerNames = MCP_SERVER_NAMES.every((name) => Object.hasOwn(policy.mcpServers ?? {}, name))
    ? MCP_SERVER_NAMES
    : Object.keys(policy.mcpServers ?? {});
  for (const name of selectedMcpServerNames) {
    const server = policy.mcpServers[name];
    lines.push("", `[mcp_servers.${quote(name)}]`);
    if (server.url) lines.push(`url = ${quote(server.url)}`);
    else {
      const launch = stdioLaunch(repoRoot, server, name, nodeExecutable);
      lines.push(
        `command = ${quote(launch.command)}`,
        `args = [${launch.args.map(quote).join(", ")}]`,
        `cwd = ${quote(launch.cwd)}`,
      );
    }
    if (server.auth !== undefined) lines.push(`auth = ${quote(server.auth)}`);
    lines.push(`enabled = ${server.enabled === true}`, "required = false");
    if (server.startupTimeoutSeconds !== undefined) lines.push(`startup_timeout_sec = ${server.startupTimeoutSeconds}`);
    if (server.toolTimeoutSeconds !== undefined) lines.push(`tool_timeout_sec = ${server.toolTimeoutSeconds}`);
    const environment = server.activation?.requestedTools === "enabledTools"
      ? { ...(server.environment ?? {}), METROPLAT_MCP_CAPABILITIES: server.enabledTools.join(",") }
      : server.environment;
    if (environment) lines.push(`env = { ${Object.entries(environment).map(([key, value]) => `${key} = ${quote(value)}`).join(", ")} }`);
    lines.push(`enabled_tools = [${server.enabledTools.map(quote).join(", ")}]`);
  }
  return `${lines.join("\n")}\n`;
}

