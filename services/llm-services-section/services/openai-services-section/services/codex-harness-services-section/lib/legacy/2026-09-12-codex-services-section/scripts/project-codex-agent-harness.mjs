export function assertMcpServerBoundary(name, server) {
  const hasHttpTransport = typeof server.url === "string" && server.url.length > 0;
  const hasSourceStdioTransport = typeof server.script === "string" && server.script.length > 0;
  const hasRegistryStdioTransport = typeof server.package === "string" && server.package.length > 0 && typeof server.bin === "string" && server.bin.length > 0;
  const hasExternalStdioTransport = typeof server.command === "string" && server.command.trim().length > 0;
  const transportCount = [hasHttpTransport, hasSourceStdioTransport, hasRegistryStdioTransport, hasExternalStdioTransport].filter(Boolean).length;
  const hasStdioTransport = hasSourceStdioTransport || hasRegistryStdioTransport || hasExternalStdioTransport;
  if (transportCount !== 1 || hasStdioTransport && (typeof server.cwd !== "string" || server.cwd.length === 0) || !Array.isArray(server.enabledTools) || server.enabledTools.length === 0) throw new Error(`harness policy has an incomplete or ambiguous ${name} boundary`);
  if (hasExternalStdioTransport && (server.script !== undefined || server.package !== undefined || server.bin !== undefined || server.url !== undefined)) throw new Error(`harness policy has an incomplete or ambiguous ${name} boundary`);
  if (server.arguments !== undefined && (!Array.isArray(server.arguments) || server.arguments.some((argument) => typeof argument !== "string"))) throw new Error(`harness policy has invalid ${name} arguments`);
  if (server.envFile !== undefined && (!hasSourceStdioTransport && !hasRegistryStdioTransport || typeof server.envFile !== "string" || server.envFile.length === 0)) throw new Error(`harness policy has an unsupported ${name} env-file boundary`);
  if (hasHttpTransport) {
    const url = new URL(server.url);
    if (!["http:", "https:"].includes(url.protocol)) throw new Error(`harness policy has an unsupported ${name} URL protocol`);
  }
  if (server.auth !== undefined && (!hasHttpTransport || server.auth !== "oauth")) throw new Error(`harness policy has an unsupported ${name} authentication boundary`);
}

