export function installHarness({ repoRoot = repoRootFromPackage(), target = repoRoot, live = false } = {}) {
  repoRoot = resolve(repoRoot); target = resolve(target);
  requireDirectory(repoRoot, "repository root"); requireDirectory(target, "target node");
  const policy = loadPolicy();
  const obsoleteAgentNames = retiredAgentNames(repoRoot, policy);
  assertExecutableBoundaries(repoRoot, policy);
  if (live) assertMcpReachability(repoRoot, policy, MCP_SERVER_NAMES);
  removeLegacySharedInstructionCopies(target);
  removeRetiredAgentProjections(target, obsoleteAgentNames);
  const codex = join(target, ".codex"); mkdirSync(codex, { recursive: true });
  const rootInstructions = join(target, "AGENTS.md");
  if (existsSync(rootInstructions) && !readFileSync(rootInstructions, "utf8").startsWith(GENERATED_AGENTS_MARKER)) throw new Error(`refusing to overwrite non-generated repository instructions: ${rootInstructions}`);
  const projection = projectRepositoryCodexHarness({
    repoRoot,
    target,
    instructions: renderRootInstructions(repoRoot, policy),
    config: renderConfig(repoRoot, policy),
    configServerNames: MCP_SERVER_NAMES,
    obsoleteMcpServerNames: OBSOLETE_MCP_SERVER_NAMES,
    obsoleteSettings: OBSOLETE_SETTINGS,
    skillSources: [],
    sharedSkillRoots: [sharedSourceRoot("skills")],
    operationSources: policy.operationSources,
    operationRoots: policy.operationRoots,
    providerAgentSources: policy.providerAgentSources ?? [],
    offices: [],
    obsoleteAgentNames,
  });
  const shared = projectSharedInstructionSources({ target, skillsPath: ".agents/skills", rulesPath: ".agents/rules" });
  return Object.freeze({ actor: policy.actor, target, config: join(codex, "config.toml"), colleagues: [], files: [...new Set([...projection.files, ...shared.files, ".codex/.codex-agent-manifest"])].sort() });
}

export function checkHarness({ repoRoot = repoRootFromPackage(), target = repoRoot, live = false } = {}) {
  repoRoot = resolve(repoRoot); target = resolve(target);
  requireDirectory(repoRoot, "repository root"); requireDirectory(target, "target node");
  for (const path of LEGACY_SHARED_INSTRUCTION_COPIES) {
    if (existsSync(join(target, path))) throw new Error(`obsolete shared instruction copy is still installed: ${path}`);
  }
  checkSharedInstructionSources({ target, skillsPath: ".agents/skills", rulesPath: ".agents/rules" });
  const scratch = mkdtempSync(join(tmpdir(), "bare-cedar-fog-codex-harness-check-"));
  try {
    const expected = installHarness({ repoRoot, target: scratch, live });
    const relativeFiles = expected.files;
    for (const file of relativeFiles) {
      if (file === ".codex/config.toml") {
        projectCodexMcpServerConfiguration({ target, config: renderConfig(repoRoot, loadPolicy()), serverNames: MCP_SERVER_NAMES, obsoleteServerNames: OBSOLETE_MCP_SERVER_NAMES, obsoleteSettings: OBSOLETE_SETTINGS, includeSettings: true, check: true });
        continue;
      }
      const actual = join(target, file), projection = join(scratch, file);
      if (!existsSync(actual)) throw new Error(`installed harness output is missing ${actual}`);
      if (readFileSync(actual, "utf8") !== readFileSync(projection, "utf8")) throw new Error(`installed harness output is stale: ${actual}`);
    }
    return Object.freeze({ actor: expected.actor, target, disposition: "projection-current", files: relativeFiles });
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

export function checkInstalledHarnessStatic({ repoRoot = repoRootFromPackage(), target = repoRoot } = {}) {
  const checked = checkHarness({ repoRoot, target, live: false });
  return Object.freeze({ ...checked, disposition: "static-projection-current" });
}

